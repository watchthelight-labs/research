"""Regenerate INDEX.md from logs/*/*/*/meta.json, machines.json and scout/. Run: python tools/index.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _rows():
    for meta in sorted((ROOT / "logs").glob("*/*/*/meta.json")):
        m = json.loads(meta.read_text(encoding="utf-8"))
        m["_dir"] = meta.parent.relative_to(ROOT).as_posix()
        yield m


def _src(m):
    s = m.get("source", "")
    if s.startswith("http"):
        tail = s.split("github.com/")[-1].replace("/issues/", "#").split("#issuecomment")[0]
        return f"[{tail}]({s})"
    return s


def build():
    rows = list(_rows())
    machines = json.loads((ROOT / "machines.json").read_text(encoding="utf-8")) if (ROOT / "machines.json").exists() else {}
    out = ["<!-- generated by tools/index.py, do not edit by hand -->", "# Index", "",
           f"{len(rows)} log sets from {len({(r['username'], r['machine']) for r in rows})} machines "
           f"and {len({r['username'] for r in rows})} people. Newest first inside each machine.", ""]
    out += ["## Machines", "", "| User | Machine | Model | macOS builds | Log sets | Last seen |", "|---|---|---|---|---|---|"]
    for key in sorted(machines):
        e = machines[key]
        n = sum(1 for r in rows if f"{r['username']}/{r['machine']}" == key)
        out.append(f"| {e['username']} | [{e['machine']}](logs/{key}) | {e.get('model', '')} | "
                   f"{', '.join(e.get('macos_builds', []))} | {n} | {e.get('last_seen', '')} |")
    for user in sorted({r["username"] for r in rows}):
        out += ["", f"## {user}"]
        for machine in sorted({r["machine"] for r in rows if r["username"] == user}):
            out += ["", f"### {machine}", "", "| Date | Source | Project | Topic | Files |", "|---|---|---|---|---|"]
            mine = sorted((r for r in rows if r["username"] == user and r["machine"] == machine),
                          key=lambda r: r["_dir"], reverse=True)
            for r in mine:
                topic = r["_dir"].rsplit("-", 1)[-1]
                out.append(f"| {r.get('collected', '')} | {_src(r)} | {r.get('project', '')} | {topic} | "
                           f"[{len(r.get('files', {}))} file(s)]({r['_dir']}) |")
    reports = sorted((ROOT / "scout" / "reports").glob("*.md"), reverse=True)
    if reports:
        out += ["", "## Upstream scout reports", ""] + [f"- [{p.stem}](scout/reports/{p.name})" for p in reports[:60]]
    with open(ROOT / "INDEX.md", "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    build()
    print("INDEX.md rebuilt")
